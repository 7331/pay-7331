// Russian (ru), polite "вы". Counted words take their plural form from Intl.PluralRules
// (https://developer.mozilla.org/en-US/docs/Web/JavaScript/Reference/Global_Objects/Intl/PluralRules).
import type { TranslatedPayerStrings } from "@/lib/payer_strings/payer_strings_type"

const russianPluralRules = new Intl.PluralRules("ru")

// "1 минуту", "2 минуты", "5 минут": the accusative after "через" and "примерно".
function countInRussian(count: number, oneForm: string, fewForm: string, manyForm: string): string {
  const pluralCategory = russianPluralRules.select(count)
  return `${count} ${pluralCategory === "one" ? oneForm : pluralCategory === "few" ? fewForm : manyForm}`
}

